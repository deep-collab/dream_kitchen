// Writes supabase/setup-all.sql: the two migrations and the menu seed in one file, so the owner
// pastes ONE file into Supabase's SQL Editor (docs/SETUP-BACKEND.md, step 1). Every part is safe
// to run again. tests/config.test.js fails if the file is out of date.
// Run: node scripts/setup-sql.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

export function setupSql() {
  const dir = 'supabase/migrations'
  const parts = readdirSync(dir)
    .filter((f) => f.endsWith('.sql'))
    .sort()
    .map((f) => [`supabase/migrations/${f}`, readFileSync(join(dir, f), 'utf8')])
  parts.push(['supabase/seed.sql', readFileSync('supabase/seed.sql', 'utf8')])
  const head = [
    '-- Dream Kitchen: the whole database setup in one file. Paste ALL of it into Supabase ->',
    '-- SQL Editor -> New query, and tap Run. Safe to run again (it never deletes orders or',
    '-- undoes Hema’s prices). Written by scripts/setup-sql.mjs from the files named below;',
    '-- do not edit this file by hand.',
    '',
  ].join('\n')
  return head + parts.map(([name, sql]) => `\n-- ===================================================================\n-- ${name}\n-- ===================================================================\n${sql.replace(/\r\n/g, '\n').trim()}\n`).join('')
}

if (import.meta.url === `file:///${process.argv[1].replaceAll('\\', '/')}` || process.argv[1]?.endsWith('setup-sql.mjs')) {
  writeFileSync('supabase/setup-all.sql', setupSql())
  console.log('supabase/setup-all.sql written')
}

// Writes docs/kannada-for-hema.md: every Kannada string with its English beside it,
// so Hema can proofread in one go. Part 1 = new or changed since Step 2 (Steps 3–4),
// Part 2 = earlier text (Steps 1–2 and the menu), which has not been checked either.
// Run: node scripts/kannada-list.mjs   (re-run after any change to the strings)
import { execSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { classes } from '../src/data/classes.js'
import { categories, occasions } from '../src/data/categories.js'
import { products } from '../src/data/products.js'
import { combos } from '../src/data/combos.js'
import { site } from '../src/config/site.js'

const STEP2_COMMIT = 'e345325' // last Step 2 commit: anything different since is "new"
const now = { en: JSON.parse(readFileSync('src/i18n/en.json', 'utf8')), kn: JSON.parse(readFileSync('src/i18n/kn.json', 'utf8')) }
const then = JSON.parse(execSync(`git show ${STEP2_COMMIT}:src/i18n/kn.json`, { encoding: 'utf8' }))

const leaves = (node, prefix = '', out = {}) => {
  if (typeof node === 'string') out[prefix] = node
  else if (Array.isArray(node)) node.forEach((v, i) => leaves(v, `${prefix}.${i + 1}`, out))
  else if (node && typeof node === 'object') Object.entries(node).forEach(([k, v]) => leaves(v, prefix ? `${prefix}.${k}` : k, out))
  return out
}
const en = leaves(now.en)
const kn = leaves(now.kn)
const old = leaves(then)

// Where each group of strings appears, in words Hema will recognise
const PLACES = {
  brand: 'Logo and tagline', nav: 'Menu and navigation', common: 'Used on many pages', seo: 'Page titles and search descriptions (Google)',
  home: 'Home page', shop: 'Shop page', product: 'Product page', cart: 'Cart', checkout: 'Checkout', success: 'Order sent page',
  track: 'Track order', about: 'Our Story page', gallery: 'Gallery page', contact: 'Contact page', faq: 'Questions & answers (FAQ)',
  notFound: 'Page not found', footer: 'Footer', mobileBar: 'Bottom bar on phones', wa: 'WhatsApp greeting', header: 'Header',
  notice: 'Pre-booking notice', mobileMenu: 'Phone menu', hours: 'Call hours', hero: 'Top of the home page', classes: 'Classes page',
  booking: 'Class booking form', booked: 'Class booking sent page', badges: 'Badges on products', customise: 'Choosing options for an item',
  combo: '3-bar combo', dates: 'Dates', callOptions: 'Call options', callback: 'Call-back request', styleguide: 'Internal test page (customers never see it)',
}
const cell = (s) => String(s).replaceAll(' ', ' ').replaceAll('|', '\\|').replace(/\n/g, ' ')

function table(rows) {
  const out = ['| # | English | ಕನ್ನಡ (please check) | Key |', '|---|---|---|---|']
  rows.forEach(([key, e, k], i) => out.push(`| ${i + 1} | ${cell(e)} | ${cell(k)} | \`${key}\` |`))
  return out.join('\n')
}
function grouped(keys) {
  const groups = {}
  for (const k of keys) (groups[k.split('.')[0]] ||= []).push([k, en[k], kn[k]])
  return Object.entries(groups)
    .filter(([g]) => g !== 'styleguide')
    .map(([g, rows]) => `### ${PLACES[g] || g}\n\n${table(rows)}`)
    .join('\n\n')
}

const all = Object.keys(kn)
const isNew = (k) => old[k] !== kn[k]
const newKeys = all.filter(isNew)
const oldKeys = all.filter((k) => !isNew(k))

// Data files: every { en, kn } pair
const pairs = (label, list) => list.filter((x) => x && x.en && x.kn).map((x, i) => [`${label} ${i + 1}`, x.en, x.kn])
const classRows = classes.flatMap((c) => pairs(c.title.en, [c.title, c.summary, ...c.learn]))
const menuRows = [
  ...categories.flatMap((c) => pairs(c.name.en, [c.name, c.intro, c.note, c.slogan, ...(c.highlights || []), ...(c.whatYouGet || []), ...c.sections.flatMap((s) => [s.name, s.itemLabel])])),
  ...products.flatMap((p) => pairs(p.name.en, [p.name, p.description, ...(p.includes || []), ...p.optionGroups.flatMap((g) => (g.id === 'flavour' ? g.choices.map((c) => c.label) : []))])),
  ...combos.flatMap((c) => pairs(c.name.en, [c.name, c.itemLabel])),
  ...pairs('Occasion', occasions.map((o) => o.label)),
]
const dedupe = (rows) => [...new Map(rows.map((r) => [`${r[1]}|${r[2]}`, r])).values()]

const count = newKeys.filter((k) => !k.startsWith('styleguide.')).length + classRows.length
const md = `# Kannada for Hema to check

Generated by \`node scripts/kannada-list.mjs\`. Do not edit by hand; send corrections and we update the site.

**How to check:** read the ಕನ್ನಡ column. If something sounds wrong or unnatural, write the better wording next to its number.
Words in \`{curly brackets}\` are filled in by the site (for example \`{phone}\` becomes ${site.phone.display}, \`{date}\` a date, \`{price}\` a price); please keep them.
Brand names (Ferrero Rocher, Nutella, Lotus Biscoff, Oreo) and "Dream Kitchen" stay in English on purpose.
WhatsApp messages to Hema are always in English, so they are not listed.

## Part 1: new in Steps 3 and 4 (${count} strings): please check these first

${grouped(newKeys)}

### Classes (sample classes: the Kannada and the English will both change once Hema gives the real classes)

${table(classRows)}

## Part 2: earlier text (Steps 1 and 2): not checked yet either

${grouped(oldKeys)}

### Menu (product names, descriptions, flavours, categories)

${table(dedupe(menuRows))}
`
writeFileSync('docs/kannada-for-hema.md', md)
console.log(`docs/kannada-for-hema.md: Part 1 ${count} strings, Part 2 ${oldKeys.filter((k) => !k.startsWith('styleguide.')).length + dedupe(menuRows).length} strings`)

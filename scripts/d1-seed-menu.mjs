// Generates d1/seed.sql from src/config/shop.js
// Run: node scripts/d1-seed-menu.mjs
import { writeFileSync } from 'node:fs'
import { products } from '../src/config/shop.js'
import { productRow } from '../netlify/lib/catalog.mjs'

const rows = products.map(productRow)
const lit = (v) => (v === null || v === undefined ? 'null' : typeof v === 'number' ? String(v) : `'${String(typeof v === 'object' ? JSON.stringify(v) : v).replace(/'/g, "''")}'`)

const cols = ['id', 'slug', 'category', 'name_en', 'name_kn', 'options', 'courier_tier', 'sort', 'image', 'updated_at']

export function generateSeedSql() {
  const lines = [
    '-- Dream Kitchen menu seed data for Cloudflare D1. Generated by: node scripts/d1-seed-menu.mjs',
    '-- Safe to run again: it never touches prices or custom photos set in admin.',
    `INSERT INTO products (${cols.join(', ')}) VALUES`,
  ]
  const valRows = rows.map((r) => {
    const rowObj = { ...r, updated_at: "strftime('%Y-%m-%dT%H:%M:%fZ', 'now')" }
    return `  (${cols.map((c) => (c === 'updated_at' ? "strftime('%Y-%m-%dT%H:%M:%fZ', 'now')" : lit(rowObj[c]))).join(', ')})`
  })
  lines.push(valRows.join(',\n'))
  const updateCols = cols.filter((c) => c !== 'id' && c !== 'updated_at')
  lines.push(`ON CONFLICT (id) DO UPDATE SET ${updateCols.map((c) => `${c} = excluded.${c}`).join(', ')};`)
  lines.push('')
  return lines.join('\n')
}

const sql = generateSeedSql()
writeFileSync('d1/seed.sql', sql)
console.log('d1/seed.sql written')

/*
  Loads the menu from the config (src/config/shop.js) into Supabase's `products` table.
  It writes the reference columns only (names, category, order, courier tier, options) and leaves
  Hema's price/sold-out/hidden overrides empty, so the config stays the source of every default.
  Running it again never undoes Hema's admin changes.

    node --env-file=.env scripts/seed-menu.mjs        upsert through the REST API (service key)
    node scripts/seed-menu.mjs --sql                  print SQL to paste in Supabase's SQL editor
                                                      (supabase/seed.sql is this output)
*/
import { products } from '../src/config/shop.js'
import { productRow } from '../netlify/lib/catalog.mjs'

const rows = products.map(productRow)
const lit = (v) => (v === null || v === undefined ? 'null' : typeof v === 'number' ? String(v) : `'${String(typeof v === 'object' ? JSON.stringify(v) : v).replace(/'/g, "''")}'`)

if (process.argv.includes('--sql')) {
  const cols = ['id', 'slug', 'category', 'name_en', 'name_kn', 'options', 'courier_tier', 'sort', 'image']
  console.log('-- Dream Kitchen menu (reference columns only). Generated by: node scripts/seed-menu.mjs --sql')
  console.log('-- Safe to run again: it never touches the prices Hema set in admin.')
  console.log(`insert into public.products (${cols.join(', ')}) values`)
  console.log(rows.map((r) => `  (${cols.map((c) => (c === 'options' ? `${lit(r[c])}::jsonb` : lit(r[c]))).join(', ')})`).join(',\n'))
  console.log(`on conflict (id) do update set ${cols.filter((c) => c !== 'id').map((c) => `${c} = excluded.${c}`).join(', ')};`)
} else {
  const url = process.env.SUPABASE_URL
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY
  if (!url || !key) {
    console.error('Set SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY (e.g. in .env, then: node --env-file=.env scripts/seed-menu.mjs), or use --sql.')
    process.exit(1)
  }
  const res = await fetch(`${url.replace(/\/$/, '')}/rest/v1/products?on_conflict=id`, {
    method: 'POST',
    headers: { apikey: key, authorization: `Bearer ${key}`, 'content-type': 'application/json', prefer: 'resolution=merge-duplicates,return=minimal' },
    body: JSON.stringify(rows),
  })
  if (!res.ok) {
    console.error('Supabase refused:', res.status, await res.text())
    process.exit(1)
  }
  console.log(`Loaded ${rows.length} products into Supabase.`)
}

// Combines d1/migrations and d1/seed.sql into d1/setup-all.sql
// Run: node scripts/d1-setup-sql.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

export function d1SetupSql() {
  const dir = 'd1/migrations'
  const parts = readdirSync(dir)
    .filter((f) => f.endsWith('.sql'))
    .sort()
    .map((f) => [`d1/migrations/${f}`, readFileSync(join(dir, f), 'utf8')])
  parts.push(['d1/seed.sql', readFileSync('d1/seed.sql', 'utf8')])
  const head = [
    '-- Dream Kitchen: complete Cloudflare D1 database setup in one file.',
    '-- For a NEW, empty database only (and the tests): wrangler d1 execute DB --local --file=d1/setup-all.sql',
    '-- A database already in use gets only its new parts: npm run d1:migrate -- --remote',
    '-- (this file would stop at "duplicate column" there; docs/CLOUDFLARE-D1-SETUP.md 2.4b).',
    '-- Written by scripts/d1-setup-sql.mjs; do not edit this file by hand.',
    '',
  ].join('\n')
  return head + parts.map(([name, sql]) => `\n-- ===================================================================\n-- ${name}\n-- ===================================================================\n${sql.replace(/\r\n/g, '\n').trim()}\n`).join('')
}

writeFileSync('d1/setup-all.sql', d1SetupSql())
console.log('d1/setup-all.sql written')
